// Copies the compiled registry's ABI and bytecode into lib/chain, so the web
// app (and its in-browser EVM) builds without a Solidity compiler.
import { readFile, writeFile } from "node:fs/promises";

const artifact = JSON.parse(
  await readFile("artifacts/contracts/CbamPassportRegistry.sol/CbamPassportRegistry.json", "utf8"),
);

const out = `// Generated by scripts/export-abi.mjs from contracts/CbamPassportRegistry.sol. Do not edit.
export const registryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const registryBytecode = "${artifact.bytecode}" as const;
`;

await writeFile("lib/chain/registry-artifact.ts", out);
console.log(`lib/chain/registry-artifact.ts: ${artifact.abi.length} ABI entries, ${(artifact.bytecode.length - 2) / 2} bytes of init code`);
